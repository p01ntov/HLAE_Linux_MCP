#!/usr/bin/env python3
"""Rebuild the original Vulkan lens shaders; runtime needs no shader compiler."""
from pathlib import Path
import argparse
import struct
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the committed header differs")
    options = parser.parse_args()
    output = ["// Generated by build_lens_shaders.py; do not edit.\n#pragma once\n#include <cstdint>\n",
              "namespace cs2_camera_lens::spirv {\n"]
    with tempfile.TemporaryDirectory(prefix="cs2-lens-shaders-") as temporary:
        for stage, name in (("vert", "Vertex"), ("frag", "Fragment")):
            target = Path(temporary) / f"lens.{stage}.spv"
            subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.1", "-o", str(target),
                            str(HERE / f"lens_effects.{stage}")], check=True, timeout=30)
            subprocess.run(["spirv-val", "--target-env", "vulkan1.1", str(target)], check=True, timeout=30)
            blob = target.read_bytes()
            words = struct.unpack(f"<{len(blob) // 4}I", blob)
            output.append(f"inline constexpr std::uint32_t {name}[] = {{\n")
            for offset in range(0, len(words), 8):
                output.append("    " + ", ".join(f"0x{word:08x}" for word in words[offset:offset + 8]) + ",\n")
            output.append("};\n")
    output.append("} // namespace cs2_camera_lens::spirv\n")
    generated = "".join(output)
    header = HERE / "lens_effects_spv.h"
    if options.check:
        if header.read_text() != generated:
            raise SystemExit("lens_effects_spv.h is stale; run build_lens_shaders.py")
    else:
        header.write_text(generated)


if __name__ == "__main__":
    main()
